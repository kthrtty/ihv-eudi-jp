// 出力エンコーディングの正本。**文脈ごとに別のエンコーダを使う**。
//
// なぜ1箇所にまとめるか（2026-08-18 の監査）: `esc()` が5ファイルに重複し、しかも
// **2種類の挙動**があった——`admin-demo.mjs` と `apply-demo.mjs` は `'` を落とさない版で、
// よりによって**申請フォームの自由入力（一番攻撃者寄りのデータ）を描く画面**がそれだった。
// 一重引用符の属性が無いので到達しなかったが、リファクタ1回で露見する。
//
// **入力側でサニタイズしない**方針を採る理由: 同じ値が HTML本文 / HTML属性 / inline JS /
// JSON API / **署名済み VC のクレーム** / CBOR の5〜6箇所へ流れる。入力時に1つの encoding で
// 潰すと他が壊れ、とりわけ VC は「その人について証明する文言」なので原文を保つ必要がある。
// 入力は**値域・形式の検証**（src/validate.mjs）、出力は**文脈ごとのエンコード**（ここ）。

/** HTML のテキスト・属性値（**二重引用符の属性**）用。`'` も落とすので一重引用符の属性でも安全。 */
export const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[c]));

/**
 * `<script>` の中に値を埋めるとき用。**HTML エスケープを使ってはいけない**——
 * script の中身は HTML デコードされないので、`esc` が作る `&lt;` や `&#39;` が
 * 文字列に literal で入る（データ破損）。
 *
 * `JSON.stringify` だけでも足りない: 値に `</script>` が含まれるとブロックが終わってしまう。
 * `<` `>` `&` を \u 形式へ、行区切り U+2028/U+2029 も落とす（JS では改行扱いで構文が壊れる）。
 */
export const js = (v) => JSON.stringify(v ?? null)
  .replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026')
  .replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

/**
 * `onclick="..."` のような**イベント属性**に値を埋めるとき用。
 * 属性値は **HTML デコードされてから JS として解析される**ので、
 * 「JS としてエンコード」→「HTML としてエスケープ」の**二段**が要る。
 * 使い方: `onclick="openCred(${jsAttr(id)})"`（引用符は付けない — js() が付ける）
 */
export const jsAttr = (v) => esc(js(v));

/** URL のクエリ値。`encodeURIComponent` の別名だが、意図を読めるようにしておく。 */
export const q = (v) => encodeURIComponent(String(v ?? ''));
