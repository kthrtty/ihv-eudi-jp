// カタログは**発生日の降順**（新しい災害ほど、いま申請される可能性が高い）
export const DISASTERS = SEED.slice()
  .sort((a, b) => (a.occurred < b.occurred ? 1 : a.occurred > b.occurred ? -1 : 0));

export const listDisasters = () => DISASTERS.map((x) => ({ ...x, codes: [...x.codes] }));
export const getDisaster = (id) => {
  const x = DISASTERS.find((y) => y.id === String(id || ''));
  return x ? { ...x, codes: [...x.codes] } : null;
};
/** その災害の対象自治体か。未知の災害・自治体は false（fail-closed）。 */
export const coversMunicipality = (disasterId, code) =>
  !!getDisaster(disasterId)?.codes.includes(String(code || ''));
/** 表示用（「令和6年能登半島地震（2024-01-01）」）。 */
export const disasterLabel = (id) => {
  const x = getDisaster(id);
  return x ? `${x.name}（${x.occurred}）` : '';
};
