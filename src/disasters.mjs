// 災害マスタ。**罹災証明書はどの自治体に申請できるか**を決める。
//
// なぜ自治体の属性ではなく災害で決めるか:
//   災害対策基本法 第90条の2 —「市町村長は、**当該市町村の地域に係る災害が発生した場合**
//   において、当該災害の被災者から申請があったときは、遅滞なく、住家の被害…の状況を
//   調査し、罹災証明書を交付しなければならない」
// つまり交付義務は全市町村が負うが、**災害というイベントに従属する**。自治体の恒常的な
// 能力として持つと「災害が起きていない種子島でも罹災証明が出せる」ように見えてしまう。
//
// **オープンデータで自動同期はできない**（2026-08-09 調査）:
//  - 内閣府「災害救助法の適用状況」は災害名・都道府県・適用日・適用市町村を載せるが **PDF のみ**
//  - さらに本質的に、**災害救助法の適用と罹災証明の交付対象は一致しない**。罹災証明は
//    法90条の2 で「災害が発生した場合」に義務が生じ、災害救助法は住家滅失世帯数などの
//    別要件。適用されない小規模災害でも罹災証明は出る＝適用一覧は部分集合にすぎない。
// よってここは**デモ用の固定データ**とし、実運用では自治体の防災システムが災害を登録する
// という位置づけにする（画面にもそう書く）。
//
// 収録は実災害5件。団体コードは総務省の公式ファイルと突合済み。
// **出典によって「対象自治体」の意味が違う**ので、`scope` に何の一覧かを持たせる:
//   - 'digital-online' … デジタル庁が公表する「災害救助法適用自治体のうち**罹災証明書の
//     オンライン申請ができる自治体**」。我々の画面と意味がぴったり一致する（最良の出典）が、
//     オンライン申請を受け付けない自治体は載らない＝罹災証明が出る自治体より**狭い**。
//   - 'kyujoho' … 内閣府「災害救助法の適用状況」からの抜粋。網羅ではなく、そもそも
//     災害救助法の適用と罹災証明の交付対象は一致しない（適用外の小規模災害でも交付される）。
// どちらにせよ**この一覧が「罹災証明が出る自治体のすべて」ではない**。画面にもそう書く。

